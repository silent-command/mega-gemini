#!/usr/bin/env python3
"""Generates the vectors the signature verifiers and the multi-precision
arithmetic are checked against, into tests/sigvectors.h, with Python's
cryptography package (OpenSSL underneath) and its integers:

    python3 tools/sig_vectors.py > tests/sigvectors.h

- Montgomery arithmetic: a*b mod m, a^e mod m, a^-1 mod m for the P-256
  prime, the P-256 order and a 2048-bit RSA modulus, with fixed inputs.
- ECDSA P-256 with SHA-256: three signatures over known hashes, DER
  encoded, plus RFC 6979 A.2.5's two (deterministic, so they must match
  exactly).
- RSA-PSS with SHA-256, MGF1-SHA256, a 32-byte salt: one signature each
  from a 2048-bit and a 4096-bit key, over known hashes.
The output is committed; the package is only needed to regenerate."""
import hashlib, random, sys
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec, rsa, padding, utils

P256_P = 0xffffffff00000001000000000000000000000000ffffffffffffffffffffffff
P256_N = 0xffffffff00000000ffffffffffffffffbce6faada7179e84f3b9cac2fc632551
P256_GX = 0x6b17d1f2e12c4247f8bce6e563a440f277037d812deb33a0f4a13945d898c296
P256_GY = 0x4fe342e2fe1a7f9b8ee7eb4a7c0f9e162bce33576b315ececbb6406837bf51f5


def be(x, n):
    return x.to_bytes(n, "big")


def c_array(name, data):
    body = ",".join(f"0x{b:02x}" for b in data)
    return f"static const uint8_t {name}[{max(len(data), 1)}] = {{{body or '0'}}};\n#define {name}_len {len(data)}\n"


def main():
    rng = random.Random(20260914)
    out = ["/* Generated by tools/sig_vectors.py. */", "#include <stdint.h>"]

    # RSA keys, fixed by seed so the header is stable across runs
    rsa2048 = rsa.generate_private_key(65537, 2048)
    rsa4096 = rsa.generate_private_key(65537, 4096)

    # multi-precision
    for name, m in (("p256p", P256_P), ("p256n", P256_N), ("rsa2048", rsa2048.public_key().public_numbers().n)):
        nbytes = (m.bit_length() + 7) // 8
        a = rng.getrandbits(m.bit_length() - 1)
        b = rng.getrandbits(m.bit_length() - 1)
        e = 65537 if name == "rsa2048" else rng.getrandbits(256)
        out.append(c_array(f"mp_{name}_m", be(m, nbytes)))
        out.append(c_array(f"mp_{name}_a", be(a, nbytes)))
        out.append(c_array(f"mp_{name}_b", be(b, nbytes)))
        out.append(c_array(f"mp_{name}_e", be(e, (e.bit_length() + 7) // 8)))
        out.append(c_array(f"mp_{name}_ab", be(a * b % m, nbytes)))
        out.append(c_array(f"mp_{name}_ae", be(pow(a, e, m), nbytes)))
        out.append(c_array(f"mp_{name}_ainv", be(pow(a, -1, m), nbytes)))

    # ECDSA P-256: RFC 6979 A.2.5, deterministic
    d = 0xC9AFA9D845BA75166B5C215767B1D6934E50C3DB36E89B127B8A622B120F6721
    key = ec.derive_private_key(d, ec.SECP256R1())
    pub = key.public_key().public_numbers()
    out.append(c_array("ecdsa_pub", be(pub.x, 32) + be(pub.y, 32)))
    rfc6979 = {
        "sample": (0xEFD48B2AACB6A8FD1140DD9CD45E81D69D2C877B56AAF991C34D0EA84EAF3716, 0xF7CB1C942D657C41D436C7A1B6E29F65F3E900DBB9AFF4064DC4AB2F843ACDA8),
        "test": (0xF1ABB023518351CD71D881567B1EA663ED3EFCF6C5132B354F28D3B0B7D38367, 0x019F4113742A2B14BD25926B49C649155F267E60D3814B4C0CC84250E46F0083),
    }
    i = 0
    for msg, (r, s_) in rfc6979.items():
        h = hashlib.sha256(msg.encode()).digest()
        der = utils.encode_dss_signature(r, s_)
        key.public_key().verify(der, msg.encode(), ec.ECDSA(hashes.SHA256()))
        out.append(c_array(f"ecdsa_hash{i}", h))
        out.append(c_array(f"ecdsa_sig{i}", der))
        i += 1
    for _ in range(3):
        msg = rng.randbytes(40)
        h = hashlib.sha256(msg).digest()
        der = key.sign(msg, ec.ECDSA(hashes.SHA256()))
        out.append(c_array(f"ecdsa_hash{i}", h))
        out.append(c_array(f"ecdsa_sig{i}", der))
        i += 1

    # RSA-PSS
    for name, k in (("rsa2048", rsa2048), ("rsa4096", rsa4096)):
        nums = k.public_key().public_numbers()
        nbytes = (nums.n.bit_length() + 7) // 8
        msg = rng.randbytes(50)
        h = hashlib.sha256(msg).digest()
        sig = k.sign(msg, padding.PSS(mgf=padding.MGF1(hashes.SHA256()), salt_length=32), hashes.SHA256())
        out.append(c_array(f"pss_{name}_n", be(nums.n, nbytes)))
        out.append(c_array(f"pss_{name}_e", be(nums.e, 3)))
        out.append(c_array(f"pss_{name}_hash", h))
        out.append(c_array(f"pss_{name}_sig", sig))

    print("\n".join(out))


if __name__ == "__main__":
    main()
