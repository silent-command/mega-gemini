#!/usr/bin/env python3
"""Extracts the test vectors the host suite checks the TLS code against,
from the RFC texts, into tests/vectors.h:

    RFC 8448 section 3 (the simple 1-RTT TLS 1.3 handshake): every
    labelled block, named heading_label, e.g. rfc8448_client_hello,
    the X25519 keys, the transcript hashes, every secret and traffic key.
    (The cipher suite there is AES-128-GCM, so the record layer itself is
    checked against a live server instead; the key schedule, the
    transcript and HKDF are checked here.)
    RFC 8439 2.8.2: the ChaCha20-Poly1305 AEAD example.
    RFC 7748 6.1: the X25519 Diffie-Hellman example.

    python3 tools/rfc_vectors.py rfc8448.txt rfc8439.txt rfc7748.txt > tests/vectors.h

The texts: https://www.rfc-editor.org/rfc/rfc8448.txt and so on. The
output is committed, so the RFCs are not needed to build."""
import re, sys

HEX_LINE = re.compile(r"^\s+((?:[0-9a-f]{2} ?)+)$")
HEADING = re.compile(r"^   \{(client|server)\}  (.*?):?\s*$")
BLOCK = re.compile(r"^\s+([A-Za-z][A-Za-z0-9 ]*?) \((\d+) octets\):\s*(.*)$")


def ident(s):
    return re.sub(r"[^a-z0-9]+", "_", s.lower()).strip("_")


def blocks_8448(text):
    start = text.index("3.  Simple 1-RTT Handshake\n")
    end = text.index("4.  Resumed 0-RTT Handshake\n")
    out, heading, label, want, hexs = [], None, None, 0, []

    def flush():
        if label is not None:
            data = bytes.fromhex("".join(hexs))
            assert len(data) == want, (heading, label, len(data), want)
            out.append((f"rfc8448_{heading}_{ident(label)}", data))

    for ln in text[start:end].split("\n"):
        m = HEADING.match(ln)
        if m:
            flush(); label = None
            heading = m.group(1) + "_" + ident(re.sub(r"\(.*?\)", "", m.group(2)))
            continue
        m = BLOCK.match(ln)
        if m and heading:
            flush()
            label, want = m.group(1), int(m.group(2))
            hexs = [m.group(3).replace(" ", "")] if HEX_LINE.match(" " + m.group(3)) else []
            continue
        m = HEX_LINE.match(ln)
        if m and label is not None:
            hexs.append(m.group(1).replace(" ", ""))
        # anything else (blank lines, page headers and footers) is skipped:
        # a block runs on until the next label or heading
    flush()
    return out


def c_array(name, data):
    body = ",".join(f"0x{b:02x}" for b in data)
    return f"static const uint8_t {name}[{max(len(data), 1)}] = {{{body or '0'}}};\n" + \
           f"#define {name}_len {len(data)}\n"


def hexbytes(s):
    """The hex of RFC 8439's dump lines: an offset, the bytes, an ASCII column."""
    return bytes.fromhex("".join(m.replace(" ", "") for m in re.findall(r"^\s*\d{3}\s+((?:[0-9a-f]{2} )*[0-9a-f]{2})", s, re.M)))


def main():
    r8448, r8439, r7748 = (open(f).read() for f in sys.argv[1:4])
    print("/* Generated by tools/rfc_vectors.py from RFC 8448, 8439 and 7748. */")
    print("#include <stdint.h>")
    seen = {}
    for name, data in blocks_8448(r8448):
        n = seen.get(name, 0); seen[name] = n + 1
        print(c_array(name if not n else f"{name}_{n}", data), end="")
    body = r8439.rindex("2.8.2.  Example and Test Vector for AEAD_CHACHA20_POLY1305")   # the body, not the contents
    sec = r8439[body:body + 8000]
    def between(a, b):
        s = sec[sec.index(a) + len(a):]
        return s[:s.index(b)]
    print(c_array("rfc8439_plaintext", hexbytes(between("Plaintext:", "AAD:"))), end="")
    print(c_array("rfc8439_aad", hexbytes(between("AAD:", "Key:"))), end="")
    print(c_array("rfc8439_key", hexbytes(between("Key:", "IV:"))), end="")
    # the 96-bit nonce is the constant followed by the IV
    nonce = hexbytes(between("32-bit fixed-common part:", "Setup for")) + hexbytes(between("IV:", "32-bit fixed-common part:"))
    print(c_array("rfc8439_nonce", nonce), end="")
    print(c_array("rfc8439_ciphertext", hexbytes(between("Ciphertext:", "AEAD Construction"))), end="")
    print(c_array("rfc8439_tag", bytes.fromhex(between("Tag:", "3.  Implementation").replace(":", "").strip())), end="")   # colon-separated, one line
    s = r7748[r7748.rindex("6.1.  Curve25519"):]   # the body, not the contents
    names = ["rfc7748_alice_priv", "rfc7748_alice_pub", "rfc7748_bob_priv", "rfc7748_bob_pub", "rfc7748_shared"]
    vals = re.findall(r":\s*\n\s*([0-9a-f]{64})", s)[:5]
    assert len(vals) == 5
    for hx, name in zip(vals, names):
        print(c_array(name, bytes.fromhex(hx)), end="")


if __name__ == "__main__":
    main()
